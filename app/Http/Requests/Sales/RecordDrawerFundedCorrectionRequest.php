<?php

namespace App\Http\Requests\Sales;

use App\Actions\Sales\RecordDrawerFundedCorrection;
use App\Domain\Commands\CommandRefused;
use App\Domain\Commands\ErrorCode;

/**
 * The FormRequest of RC-05 `sale_correction.drawer_funded` (INTERACTION_CONTRACTS RC-05; TECHNICAL_RULES
 * sections 5, 11.1 to 11.3; COPY_DECK section 16.1; BR-RFD-02, BR-RFD-05 to BR-RFD-07; TASK-034 scope item
 * 1), on the base of a Sale's correction (CorrectionRequest): the lines and the reason, and `payout`, always
 * present, with only `sessionId`, the OPEN cash session whose drawer pays the refund, a JSON whole number
 * (TR-VAL-06). The payout takes no method, amount, reference or funding source: a drawer-funded payout is
 * CASH, its amount the lines' sum, its reference generated by the server and its source the drawer
 * (BR-RFD-05; TR-VAL-03), and the allowlist refuses them. Whether the session exists, is OPEN and holds the
 * expected cash is the Action's to check, under its lock.
 *
 * Refused before any lock (RC-05): a Sale line named twice, VALIDATION_FAILED at each repeated line; no line
 * that refunds money or returns goods, at `payload.lines`; no money refunded, since RC-05 needs a refund
 * above zero, VALIDATION_FAILED without a field, since COPY_DECK names no text for it and no page sends it;
 * anything else that fails, at its fields.
 */
final class RecordDrawerFundedCorrectionRequest extends CorrectionRequest
{
    public function operation(): string
    {
        return RecordDrawerFundedCorrection::OPERATION;
    }

    /**
     * @return array<string, mixed>
     */
    protected function payoutRules(): array
    {
        return [
            'payout' => ['required', 'array'],
            'payout.sessionId' => ['required_with:payload.payout', 'integer', 'min:1'],
        ];
    }

    /**
     * @return array<string, array{0: string, 1?: array<string, string|int>}>
     */
    protected function payoutKeys(): array
    {
        return [
            'payload.payout.required' => ['ux.validation.required'],
            'payload.payout.sessionId.required_with' => ['ux.validation.required'],
            'payload.payout.sessionId.integer' => ['ux.validation.choose_one'],
            'payload.payout.sessionId.min' => ['ux.validation.choose_one'],
        ];
    }

    /**
     * A session that is no JSON whole number, or no money refunded.
     */
    protected function payoutWrong(): bool
    {
        $session = $this->input('payload.payout.sessionId');

        return ($session !== null && ! is_int($session)) || ! $this->refundsMoney();
    }

    /**
     * With every field valid and some line moving: no money refunded, a refusal without a field.
     */
    protected function payoutRefusal(): ?CommandRefused
    {
        return $this->anyLineMoves() && ! $this->refundsMoney() ? CommandRefused::of(ErrorCode::ValidationFailed) : null;
    }
}
